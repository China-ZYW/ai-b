package com.aibi.module.chat.skill;

/**
 * 问数技能（Skill）：把"一个问题怎么被回答"抽象为可插拔的独立策略。
 *
 * <p><b>为什么拆技能</b>：原问数链路是一条固定的流水线（意图 → 裁剪 → Prompt → LLM → 校验 → 执行），
 * 无论问题多简单都必须走一遍 LLM，既慢又费配额，且"已经验证过的问法"每次都要重新猜。
 * 技能化后，链路变为"路由 → 某个技能执行 → 统一的后置编排（脱敏 / 图表 / 解读 / 校验 / 历史）"，
 * 于是可以：① 免 LLM 的确定性技能优先命中（直连 SQL、指标直达、样例复用、数据字典），秒级返回且口径稳定；
 * ② 新增答问能力只需加一个实现类，不改动既有链路；③ 每个技能的命中率可单独观测与运营。
 *
 * <p><b>契约</b>：技能只负责"产出一次查询执行结果"，不做脱敏、图表、解读、落库——
 * 这些由 {@code ChatService} 统一后置处理，保证所有技能出口一致（权限、展示名、历史都不会被绕过）。
 *
 * <p><b>解析与执行分离（V4.1）</b>：技能只暴露 {@link #plan} 一次调用，返回的 {@link SkillPlan}
 * 既回答"能不能答"，也用闭包携带"已经查到的东西"，由编排层择机 {@link SkillPlan#run()}。
 * 这样避免了"判定查一遍库、执行再查一遍库"的经典浪费，实现方务必把 {@code plan} 内查到的
 * 实体直接闭包进 runner，<b>严禁在 runner 里再次查询</b>。
 *
 * <p><b>隔离与安全</b>：SQL 一律经 {@code SqlValidator} 复校、经数据源适配器只读执行；
 * 指标/样例查询由租户拦截器自动隔离，跨租户数据不可见。
 */
public interface AskSkill {

    /** 技能唯一编码（如 {@code direct_sql}），用于路由强制指定与历史留痕。 */
    String code();

    /** 技能中文名（前端展示"本次由 XX 回答"）。 */
    String name();

    /** 技能能力说明（技能清单接口透出，供管理员理解各技能职责）。 */
    String description();

    /**
     * 路由优先级：越小越先判定。确定性技能（直连 SQL / 指标 / 样例 / 数据字典）排在前，
     * 兜底的 NL2SQL 排在最后（恒命中）。
     */
    int order();

    /** 技能总开关（关闭后不参与路由；兜底技能不允许关闭）。 */
    default boolean enabled() {
        return true;
    }

    /**
     * 是否免 LLM：命中即复用已验证产物（用户自写 SQL、已存指标 SQL、人工样例 SQL、已有元数据），
     * 全程不调用大模型。免 LLM 的技能<b>不消耗问数配额</b>——既省成本，也鼓励把问法沉淀为指标。
     */
    default boolean llmFree() {
        return false;
    }

    /**
     * 是否允许被"质量校验驱动重试"重写。免 LLM 的确定性技能默认不允许：
     * 用户给定 SQL 与已存指标口径是权威的，AI 校验无权改写（改写会造成"问题 ≠ 执行口径"）。
     */
    default boolean rewritable() {
        return !llmFree();
    }

    /**
     * 解析本次问数：判定能否处理，并把已查到的资源闭包进返回的计划。
     *
     * <p>实现必须<b>廉价且无副作用</b>——只允许文本判定与本地查表；路由会串行调用全部技能，
     * 任何昂贵操作都会放大到每一次问数。SQL 的执行必须推迟到 {@link SkillPlan#run()}，
     * 否则"仅仅在试探能否命中"就会变成"真的跑了一遍查询"。
     *
     * @param ctx 问数上下文（问题、会话、多轮、进度、统计、数据源、租户）
     * @return 命中返回带执行动作的 {@link SkillPlan}；不适用返回 {@link SkillPlan#NO}
     */
    SkillPlan plan(AskContext ctx);
}
