def reset_random():
    """固定随机种子：重复执行生成完全相同的一批数据，便于回归比对。"""
    random.seed(SEED)


def months_back(n, end=TODAY):
    """最近 n 个自然月的 'YYYY-MM' 列表（升序，含 end 所在月）。"""
    out = []
    y, m = end.year, end.month
    for _ in range(n):
        out.append("%04d-%02d" % (y, m))
        m -= 1
        if m == 0:
            m, y = 12, y - 1
    return list(reversed(out))


def month_of(d):
    return "%04d-%02d" % (d.year, d.month)


def rnd_date(start, end):
    return start + timedelta(days=random.randint(0, (end - start).days))


def rnd_dt(d, start_hour=8, end_hour=23):
    """给定日期上的随机时刻（落在营业时段内，避免出现凌晨 3 点下单这类不真实数据）。"""
    return datetime(d.year, d.month, d.day,
                    random.randint(start_hour, end_hour), random.randint(0, 59), random.randint(0, 59))


def pick(items):
    return random.choice(items)


def weighted(choices, weights):
    """按权重随机取一个元素（渠道、状态、品类等分布都不能是均匀的，否则数据没有业务形态）。"""
    return random.choices(choices, weights=weights, k=1)[0]


def insert(cur, table, columns, rows, batch_size=1000):
    """分批 executemany 插入。远程库往返成本高，批太小会慢到不可接受。"""
    if not rows:
        return 0
    sql = "INSERT INTO `%s` (%s) VALUES (%s)" % (
        table, ",".join("`%s`" % c for c in columns), ",".join(["%s"] * len(columns)))
    for i in range(0, len(rows), batch_size):
        cur.executemany(sql, rows[i:i + batch_size])
    return len(rows)


def count(cur, table):
    cur.execute("SELECT COUNT(*) FROM `%s`" % table)
    return cur.fetchone()[0]


